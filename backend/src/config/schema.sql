-- =============================================================================
-- schema.sql
-- PostgreSQL 14+ Normalized Schema (42 Tables in `public`, employment_type merged into employees)
-- MSU-Naawan Automated Payroll Management System
-- =============================================================================

-- =============================================================================
-- 0. LOOKUP TABLES (2)
-- =============================================================================

CREATE TABLE IF NOT EXISTS slip_types (
  id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(50)  NOT NULL UNIQUE, -- ORAS, BURAS
  name VARCHAR(150) NOT NULL
);

CREATE TABLE IF NOT EXISTS statuses (
  id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category VARCHAR(50)  NOT NULL,
  code     VARCHAR(50)  NOT NULL,
  name     VARCHAR(150) NOT NULL,
  CONSTRAINT uq_statuses_category_code UNIQUE (category, code)
);

-- =============================================================================
-- 1. CORE EMPLOYEE, AUTH, ACCESS & NOTIFICATIONS (6)
-- =============================================================================

CREATE TABLE IF NOT EXISTS employees (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_no     VARCHAR(50)  NOT NULL UNIQUE,
  last_name       VARCHAR(100) NOT NULL,
  first_name      VARCHAR(100) NOT NULL,
  middle_name     VARCHAR(100) NULL,
  birth_date      DATE         NOT NULL,
  employment_type VARCHAR(50)  NOT NULL DEFAULT 'REGULAR'
    CHECK (employment_type IN ('REGULAR', 'CONTRACTUAL', 'JO', 'LECTURER')),
  bank_account_no VARCHAR(50)  NULL,
  tin             VARCHAR(50)  NULL,
  gsis_no         VARCHAR(50)  NULL,
  philhealth_no   VARCHAR(50)  NULL,
  pagibig_no      VARCHAR(50)  NULL,
  status_id       BIGINT       NOT NULL,
  CONSTRAINT fk_employees_status
    FOREIGN KEY (status_id) REFERENCES statuses (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_employees_status_id ON employees (status_id);
CREATE INDEX IF NOT EXISTS idx_employees_employment_type ON employees (employment_type);

CREATE TABLE IF NOT EXISTS users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id   BIGINT       NULL UNIQUE, -- nullable, 1:1 with employees
  username      VARCHAR(100) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  email         VARCHAR(255) NOT NULL UNIQUE,
  is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
  last_login_at TIMESTAMPTZ  NULL,
  CONSTRAINT fk_users_employee
    FOREIGN KEY (employee_id) REFERENCES employees (id)
    ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS roles (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(100) NOT NULL UNIQUE,
  description VARCHAR(255) NULL
);

CREATE TABLE IF NOT EXISTS user_roles (
  user_id BIGINT NOT NULL,
  role_id BIGINT NOT NULL,
  PRIMARY KEY (user_id, role_id),
  CONSTRAINT fk_user_roles_user
    FOREIGN KEY (user_id) REFERENCES users (id)
    ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_user_roles_role
    FOREIGN KEY (role_id) REFERENCES roles (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_user_roles_role_id ON user_roles (role_id);

CREATE TABLE IF NOT EXISTS audit_logs (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT       NOT NULL,
  action      VARCHAR(100) NOT NULL,
  entity_type VARCHAR(100) NOT NULL,
  entity_id   BIGINT       NOT NULL,
  old_values  JSONB        NULL,
  new_values  JSONB        NULL,
  ip_address  VARCHAR(45)  NULL,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_audit_logs_user
    FOREIGN KEY (user_id) REFERENCES users (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_audit_logs_user_id ON audit_logs (user_id);
CREATE INDEX IF NOT EXISTS idx_audit_logs_entity ON audit_logs (entity_type, entity_id);
CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at ON audit_logs (created_at);

CREATE TABLE IF NOT EXISTS notifications (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT       NOT NULL,
  title       VARCHAR(200) NOT NULL,
  message     TEXT         NOT NULL,
  entity_type VARCHAR(50)  NULL,
  entity_id   BIGINT       NULL,
  is_read     BOOLEAN      NOT NULL DEFAULT FALSE,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_notifications_user
    FOREIGN KEY (user_id) REFERENCES users (id)
    ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_notifications_user_unread ON notifications (user_id, is_read);

-- =============================================================================
-- 2. ORGANIZATIONAL UNITS, SIGNATORIES, APPOINTMENTS & PAY COMPONENTS (8)
-- =============================================================================

CREATE TABLE IF NOT EXISTS offices (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code         VARCHAR(50)  NOT NULL UNIQUE,
  name         VARCHAR(200) NOT NULL,
  head_user_id BIGINT       NULL,
  CONSTRAINT fk_offices_head_user
    FOREIGN KEY (head_user_id) REFERENCES users (id)
    ON DELETE SET NULL ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_offices_head_user_id ON offices (head_user_id);

CREATE TABLE IF NOT EXISTS cost_centers (
  id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(50)  NOT NULL UNIQUE,
  name VARCHAR(200) NOT NULL
);

CREATE TABLE IF NOT EXISTS cost_center_signatories (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cost_center_id  BIGINT       NOT NULL,
  user_id         BIGINT       NOT NULL,
  document_type   VARCHAR(20)  NOT NULL CHECK (document_type IN ('PAYROLL', 'ORAS', 'BURAS', 'DV', 'ADA', 'ADCA')),
  signatory_order INTEGER      NOT NULL DEFAULT 1,
  designation     VARCHAR(150) NULL,
  is_active       BOOLEAN      NOT NULL DEFAULT TRUE,
  CONSTRAINT uq_cc_signatory UNIQUE (cost_center_id, user_id, document_type, signatory_order),
  CONSTRAINT fk_cc_signatories_cost_center
    FOREIGN KEY (cost_center_id) REFERENCES cost_centers (id)
    ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_cc_signatories_user
    FOREIGN KEY (user_id) REFERENCES users (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_cc_signatories_cc_doc ON cost_center_signatories (cost_center_id, document_type);
CREATE INDEX IF NOT EXISTS idx_cc_signatories_user_id ON cost_center_signatories (user_id);

CREATE TABLE IF NOT EXISTS funds (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code         VARCHAR(50)  NOT NULL UNIQUE, -- 01, 05, 07
  name         VARCHAR(200) NOT NULL,
  slip_type_id BIGINT       NOT NULL,
  CONSTRAINT fk_funds_slip_type
    FOREIGN KEY (slip_type_id) REFERENCES slip_types (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_funds_slip_type_id ON funds (slip_type_id);

CREATE TABLE IF NOT EXISTS payroll_periods (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label               VARCHAR(100) NOT NULL,
  period_start        DATE         NOT NULL,
  period_end          DATE         NOT NULL,
  submission_deadline DATE         NOT NULL,
  status_id           BIGINT       NOT NULL,
  CONSTRAINT fk_payroll_periods_status
    FOREIGN KEY (status_id) REFERENCES statuses (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_payroll_periods_status_id ON payroll_periods (status_id);

CREATE TABLE IF NOT EXISTS appointments (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id     BIGINT         NOT NULL,
  office_id       BIGINT         NOT NULL,
  cost_center_id  BIGINT         NOT NULL,
  fund_id         BIGINT         NOT NULL,
  employment_type VARCHAR(50)    NOT NULL DEFAULT 'REGULAR'
    CHECK (employment_type IN ('REGULAR', 'CONTRACTUAL', 'JO', 'LECTURER')),
  position_title  VARCHAR(150)   NOT NULL,
  salary_grade    VARCHAR(20)    NULL,
  step_increment  INTEGER        NULL,
  monthly_rate    NUMERIC(14, 2) NULL,
  daily_rate      NUMERIC(14, 2) NULL,
  hourly_rate     NUMERIC(14, 2) NULL,
  effective_from  DATE           NOT NULL,
  effective_to    DATE           NULL,
  CONSTRAINT fk_appointments_employee
    FOREIGN KEY (employee_id) REFERENCES employees (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_appointments_office
    FOREIGN KEY (office_id) REFERENCES offices (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_appointments_cost_center
    FOREIGN KEY (cost_center_id) REFERENCES cost_centers (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_appointments_fund
    FOREIGN KEY (fund_id) REFERENCES funds (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_appointments_employee_id ON appointments (employee_id);
CREATE INDEX IF NOT EXISTS idx_appointments_office_id ON appointments (office_id);
CREATE INDEX IF NOT EXISTS idx_appointments_cost_center_id ON appointments (cost_center_id);
CREATE INDEX IF NOT EXISTS idx_appointments_fund_id ON appointments (fund_id);
CREATE INDEX IF NOT EXISTS idx_appointments_employment_type ON appointments (employment_type);

CREATE TABLE IF NOT EXISTS pay_components (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code         VARCHAR(50)  NOT NULL UNIQUE,
  name         VARCHAR(150) NOT NULL,
  type         VARCHAR(20)  NOT NULL CHECK (type IN ('EARNING', 'ALLOWANCE', 'DEDUCTION', 'ADJUSTMENT')),
  is_statutory BOOLEAN      NOT NULL DEFAULT FALSE,
  calc_method  VARCHAR(20)  NOT NULL CHECK (calc_method IN ('FIXED', 'PERCENT', 'TABLE'))
);

CREATE TABLE IF NOT EXISTS employee_components (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id    BIGINT         NOT NULL,
  component_id   BIGINT         NOT NULL,
  period_id      BIGINT         NULL,
  is_one_time    BOOLEAN        NOT NULL DEFAULT FALSE,
  amount         NUMERIC(14, 2) NOT NULL,
  effective_from DATE           NOT NULL,
  effective_to   DATE           NULL,
  CONSTRAINT fk_employee_components_employee
    FOREIGN KEY (employee_id) REFERENCES employees (id)
    ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_employee_components_component
    FOREIGN KEY (component_id) REFERENCES pay_components (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_employee_components_period
    FOREIGN KEY (period_id) REFERENCES payroll_periods (id)
    ON DELETE SET NULL ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_employee_components_emp_id ON employee_components (employee_id);
CREATE INDEX IF NOT EXISTS idx_employee_components_comp_id ON employee_components (component_id);
CREATE INDEX IF NOT EXISTS idx_employee_components_period_id ON employee_components (period_id);

-- =============================================================================
-- 3. DOCUMENT TRACKING (7)
-- =============================================================================

CREATE TABLE IF NOT EXISTS document_types (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(150) NOT NULL,
  is_required BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS document_type_employment_types (
  document_type_id BIGINT      NOT NULL,
  employment_type  VARCHAR(50) NOT NULL
    CHECK (employment_type IN ('REGULAR', 'CONTRACTUAL', 'JO', 'LECTURER')),
  PRIMARY KEY (document_type_id, employment_type),
  CONSTRAINT fk_dtet_document_type
    FOREIGN KEY (document_type_id) REFERENCES document_types (id)
    ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_dtet_employment_type ON document_type_employment_types (employment_type);

CREATE TABLE IF NOT EXISTS document_submissions (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period_id    BIGINT      NOT NULL,
  office_id    BIGINT      NOT NULL,
  employee_id  BIGINT      NOT NULL,
  submitted_by BIGINT      NOT NULL,
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  is_late      BOOLEAN     NOT NULL DEFAULT FALSE,
  status_id    BIGINT      NOT NULL,
  CONSTRAINT fk_doc_submissions_period
    FOREIGN KEY (period_id) REFERENCES payroll_periods (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_doc_submissions_office
    FOREIGN KEY (office_id) REFERENCES offices (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_doc_submissions_employee
    FOREIGN KEY (employee_id) REFERENCES employees (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_doc_submissions_submitted_by
    FOREIGN KEY (submitted_by) REFERENCES users (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_doc_submissions_status
    FOREIGN KEY (status_id) REFERENCES statuses (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_doc_submissions_period_office ON document_submissions (period_id, office_id);
CREATE INDEX IF NOT EXISTS idx_doc_submissions_office_id ON document_submissions (office_id);
CREATE INDEX IF NOT EXISTS idx_doc_submissions_employee_id ON document_submissions (employee_id);
CREATE INDEX IF NOT EXISTS idx_doc_submissions_submitted_by ON document_submissions (submitted_by);
CREATE INDEX IF NOT EXISTS idx_doc_submissions_status_id ON document_submissions (status_id);

CREATE TABLE IF NOT EXISTS submission_items (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id    BIGINT       NOT NULL,
  document_type_id BIGINT       NOT NULL,
  file_path        VARCHAR(500) NULL,
  is_complete      BOOLEAN      NOT NULL DEFAULT FALSE,
  remarks          VARCHAR(500) NULL,
  CONSTRAINT fk_submission_items_submission
    FOREIGN KEY (submission_id) REFERENCES document_submissions (id)
    ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_submission_items_doc_type
    FOREIGN KEY (document_type_id) REFERENCES document_types (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_submission_items_submission_id ON submission_items (submission_id);
CREATE INDEX IF NOT EXISTS idx_submission_items_doc_type_id ON submission_items (document_type_id);

CREATE TABLE IF NOT EXISTS logbook_verifications (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id      BIGINT       NOT NULL,
  verification_stage VARCHAR(20)  NOT NULL CHECK (verification_stage IN ('SUPERVISOR', 'HR')),
  verified_by        BIGINT       NOT NULL,
  verified_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  result             VARCHAR(20)  NOT NULL CHECK (result IN ('PASSED', 'FAILED')),
  remarks            VARCHAR(500) NULL,
  CONSTRAINT uq_logbook_submission_stage UNIQUE (submission_id, verification_stage),
  CONSTRAINT fk_logbook_verifications_submission
    FOREIGN KEY (submission_id) REFERENCES document_submissions (id)
    ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_logbook_verifications_verified_by
    FOREIGN KEY (verified_by) REFERENCES users (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_logbook_verifications_verified_by ON logbook_verifications (verified_by);

CREATE TABLE IF NOT EXISTS transmittals (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transmittal_no VARCHAR(100) NOT NULL UNIQUE,
  from_office_id BIGINT       NOT NULL,
  to_office_id   BIGINT       NOT NULL,
  created_by     BIGINT       NOT NULL,
  sent_at        TIMESTAMPTZ  NULL,
  received_at    TIMESTAMPTZ  NULL,
  status_id      BIGINT       NOT NULL,
  CONSTRAINT fk_transmittals_from_office
    FOREIGN KEY (from_office_id) REFERENCES offices (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_transmittals_to_office
    FOREIGN KEY (to_office_id) REFERENCES offices (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_transmittals_created_by
    FOREIGN KEY (created_by) REFERENCES users (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_transmittals_status
    FOREIGN KEY (status_id) REFERENCES statuses (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_transmittals_from_office ON transmittals (from_office_id);
CREATE INDEX IF NOT EXISTS idx_transmittals_to_office ON transmittals (to_office_id);
CREATE INDEX IF NOT EXISTS idx_transmittals_created_by ON transmittals (created_by);
CREATE INDEX IF NOT EXISTS idx_transmittals_status_id ON transmittals (status_id);

CREATE TABLE IF NOT EXISTS transmittal_items (
  transmittal_id BIGINT NOT NULL,
  submission_id  BIGINT NOT NULL,
  PRIMARY KEY (transmittal_id, submission_id),
  CONSTRAINT fk_transmittal_items_transmittal
    FOREIGN KEY (transmittal_id) REFERENCES transmittals (id)
    ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_transmittal_items_submission
    FOREIGN KEY (submission_id) REFERENCES document_submissions (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_transmittal_items_submission_id ON transmittal_items (submission_id);

-- =============================================================================
-- 4. ATTENDANCE, LEAVE & PAYROLL COMPUTATION (6)
-- =============================================================================

CREATE TABLE IF NOT EXISTS dtr_imports (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period_id   BIGINT       NOT NULL,
  office_id   BIGINT       NOT NULL,
  imported_by BIGINT       NOT NULL,
  file_name   VARCHAR(255) NOT NULL,
  row_count   INTEGER      NOT NULL DEFAULT 0,
  error_count INTEGER      NOT NULL DEFAULT 0,
  imported_at TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_dtr_imports_period
    FOREIGN KEY (period_id) REFERENCES payroll_periods (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_dtr_imports_office
    FOREIGN KEY (office_id) REFERENCES offices (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_dtr_imports_imported_by
    FOREIGN KEY (imported_by) REFERENCES users (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_dtr_imports_period_office ON dtr_imports (period_id, office_id);
CREATE INDEX IF NOT EXISTS idx_dtr_imports_office_id ON dtr_imports (office_id);
CREATE INDEX IF NOT EXISTS idx_dtr_imports_imported_by ON dtr_imports (imported_by);

CREATE TABLE IF NOT EXISTS dtr_records (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  import_id         BIGINT        NULL,
  employee_id       BIGINT        NOT NULL,
  work_date         DATE          NOT NULL,
  time_in           TIME          NULL,
  time_out          TIME          NULL,
  late_minutes      INTEGER       NOT NULL DEFAULT 0,
  undertime_minutes INTEGER       NOT NULL DEFAULT 0,
  is_absent         BOOLEAN       NOT NULL DEFAULT FALSE,
  hours_worked      NUMERIC(6, 2) NOT NULL DEFAULT 0.00,
  entry_source      VARCHAR(20)   NOT NULL DEFAULT 'IMPORT' CHECK (entry_source IN ('IMPORT', 'MANUAL')),
  verified_by       BIGINT        NULL,
  verified_at       TIMESTAMPTZ   NULL,
  CONSTRAINT fk_dtr_records_import
    FOREIGN KEY (import_id) REFERENCES dtr_imports (id)
    ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_dtr_records_employee
    FOREIGN KEY (employee_id) REFERENCES employees (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_dtr_records_verified_by
    FOREIGN KEY (verified_by) REFERENCES users (id)
    ON DELETE SET NULL ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_dtr_records_import_id ON dtr_records (import_id);
CREATE INDEX IF NOT EXISTS idx_dtr_records_emp_date ON dtr_records (employee_id, work_date);
CREATE INDEX IF NOT EXISTS idx_dtr_records_verified_by ON dtr_records (verified_by);

CREATE TABLE IF NOT EXISTS leave_records (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id BIGINT        NOT NULL,
  leave_type  VARCHAR(20)   NOT NULL CHECK (leave_type IN ('VL', 'SL', 'CTO', 'SPL', 'MATERNITY', 'PATERNITY', 'LWOP', 'OTHER')),
  start_date  DATE          NOT NULL,
  end_date    DATE          NOT NULL,
  days_count  NUMERIC(5, 2) NOT NULL,
  is_with_pay BOOLEAN       NOT NULL DEFAULT TRUE,
  approved_by BIGINT        NULL,
  approved_at TIMESTAMPTZ   NULL,
  status_id   BIGINT        NOT NULL,
  CONSTRAINT fk_leave_records_employee
    FOREIGN KEY (employee_id) REFERENCES employees (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_leave_records_approved_by
    FOREIGN KEY (approved_by) REFERENCES users (id)
    ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_leave_records_status
    FOREIGN KEY (status_id) REFERENCES statuses (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_leave_records_emp_dates ON leave_records (employee_id, start_date, end_date);
CREATE INDEX IF NOT EXISTS idx_leave_records_approved_by ON leave_records (approved_by);
CREATE INDEX IF NOT EXISTS idx_leave_records_status_id ON leave_records (status_id);

CREATE TABLE IF NOT EXISTS payroll_batches (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  period_id        BIGINT         NOT NULL,
  office_id        BIGINT         NOT NULL,
  cost_center_id   BIGINT         NOT NULL,
  fund_id          BIGINT         NOT NULL,
  employment_type  VARCHAR(50)    NOT NULL DEFAULT 'REGULAR'
    CHECK (employment_type IN ('REGULAR', 'CONTRACTUAL', 'JO', 'LECTURER')),
  batch_no         VARCHAR(100)   NOT NULL UNIQUE,
  total_gross      NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
  total_deductions NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
  total_net        NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
  status_id        BIGINT         NOT NULL,
  CONSTRAINT fk_payroll_batches_period
    FOREIGN KEY (period_id) REFERENCES payroll_periods (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_payroll_batches_office
    FOREIGN KEY (office_id) REFERENCES offices (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_payroll_batches_cost_center
    FOREIGN KEY (cost_center_id) REFERENCES cost_centers (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_payroll_batches_fund
    FOREIGN KEY (fund_id) REFERENCES funds (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_payroll_batches_status
    FOREIGN KEY (status_id) REFERENCES statuses (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_payroll_batches_period_id ON payroll_batches (period_id);
CREATE INDEX IF NOT EXISTS idx_payroll_batches_office_id ON payroll_batches (office_id);
CREATE INDEX IF NOT EXISTS idx_payroll_batches_cost_center_id ON payroll_batches (cost_center_id);
CREATE INDEX IF NOT EXISTS idx_payroll_batches_fund_id ON payroll_batches (fund_id);
CREATE INDEX IF NOT EXISTS idx_payroll_batches_emp_type ON payroll_batches (employment_type);
CREATE INDEX IF NOT EXISTS idx_payroll_batches_status_id ON payroll_batches (status_id);

CREATE TABLE IF NOT EXISTS payroll_items (
  id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id                 BIGINT         NOT NULL,
  appointment_id           BIGINT         NOT NULL,
  days_worked              NUMERIC(6, 2)  NOT NULL DEFAULT 0.00,
  absences                 NUMERIC(6, 2)  NOT NULL DEFAULT 0.00,
  late_undertime_deduction NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
  proration_factor         NUMERIC(6, 4)  NOT NULL DEFAULT 1.0000,
  gross_pay                NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
  total_deductions         NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
  net_pay                  NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
  CONSTRAINT fk_payroll_items_batch
    FOREIGN KEY (batch_id) REFERENCES payroll_batches (id)
    ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_payroll_items_appointment
    FOREIGN KEY (appointment_id) REFERENCES appointments (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_payroll_items_batch_id ON payroll_items (batch_id);
CREATE INDEX IF NOT EXISTS idx_payroll_items_appointment_id ON payroll_items (appointment_id);

CREATE TABLE IF NOT EXISTS payroll_item_lines (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payroll_item_id BIGINT         NOT NULL,
  component_id    BIGINT         NOT NULL,
  amount          NUMERIC(14, 2) NOT NULL,
  CONSTRAINT fk_payroll_item_lines_item
    FOREIGN KEY (payroll_item_id) REFERENCES payroll_items (id)
    ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_payroll_item_lines_component
    FOREIGN KEY (component_id) REFERENCES pay_components (id)
