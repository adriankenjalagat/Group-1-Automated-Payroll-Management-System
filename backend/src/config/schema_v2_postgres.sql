  effective_to   DATE           NULL,
  CONSTRAINT fk_employee_components_employee
    FOREIGN KEY (employee_id) REFERENCES payroll_v2.employees (id)
    ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_employee_components_component
    FOREIGN KEY (component_id) REFERENCES payroll_v2.pay_components (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_employee_components_period
    FOREIGN KEY (period_id) REFERENCES payroll_v2.payroll_periods (id)
    ON DELETE SET NULL ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_employee_components_emp_id ON payroll_v2.employee_components (employee_id);
CREATE INDEX IF NOT EXISTS idx_employee_components_comp_id ON payroll_v2.employee_components (component_id);
CREATE INDEX IF NOT EXISTS idx_employee_components_period_id ON payroll_v2.employee_components (period_id);

