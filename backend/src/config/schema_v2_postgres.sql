-- =============================================================================
-- schema_v2_postgres.sql
-- PostgreSQL 14+ Normalized Schema (All 43 Tables in schema `payroll_v2`)
-- MSU-Naawan Automated Payroll Management System
-- Non-breaking integration alongside existing `public` operational tables.
-- =============================================================================

CREATE SCHEMA IF NOT EXISTS payroll_v2;

-- =============================================================================
-- 0. LOOKUP TABLES
-- =============================================================================

CREATE TABLE IF NOT EXISTS payroll_v2.employment_types (
  id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(50)  NOT NULL UNIQUE, -- REGULAR, CONTRACTUAL, JO, LECTURER
  name VARCHAR(150) NOT NULL
);

CREATE TABLE IF NOT EXISTS payroll_v2.slip_types (
  id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(50)  NOT NULL UNIQUE, -- ORAS, BURAS
  name VARCHAR(150) NOT NULL
);

CREATE TABLE IF NOT EXISTS payroll_v2.statuses (
  id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category VARCHAR(50)  NOT NULL,
  code     VARCHAR(50)  NOT NULL,
  name     VARCHAR(150) NOT NULL,
  CONSTRAINT uq_statuses_category_code UNIQUE (category, code)
);

-- =============================================================================
-- 1. CORE EMPLOYEE, AUTH, ACCESS & NOTIFICATIONS
-- =============================================================================

CREATE TABLE IF NOT EXISTS payroll_v2.employees (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_no     VARCHAR(50)  NOT NULL UNIQUE,
  last_name       VARCHAR(100) NOT NULL,
  first_name      VARCHAR(100) NOT NULL,
  middle_name     VARCHAR(100) NULL,
  birth_date      DATE         NOT NULL,
  bank_account_no VARCHAR(50)  NULL,
  tin             VARCHAR(50)  NULL,
  gsis_no         VARCHAR(50)  NULL,
  philhealth_no   VARCHAR(50)  NULL,
  pagibig_no      VARCHAR(50)  NULL,
  status_id       BIGINT       NOT NULL,
  CONSTRAINT fk_employees_status
    FOREIGN KEY (status_id) REFERENCES payroll_v2.statuses (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_employees_status_id ON payroll_v2.employees (status_id);

CREATE TABLE IF NOT EXISTS payroll_v2.users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id   BIGINT       NULL UNIQUE, -- nullable, 1:1 with employees
  username      VARCHAR(100) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  email         VARCHAR(255) NOT NULL UNIQUE,
  is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
  last_login_at TIMESTAMPTZ  NULL,
  CONSTRAINT fk_users_employee
    FOREIGN KEY (employee_id) REFERENCES payroll_v2.employees (id)
    ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS payroll_v2.roles (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(100) NOT NULL UNIQUE,
  description VARCHAR(255) NULL
);

CREATE TABLE IF NOT EXISTS payroll_v2.user_roles (
  user_id BIGINT NOT NULL,
  role_id BIGINT NOT NULL,
  PRIMARY KEY (user_id, role_id),
  CONSTRAINT fk_user_roles_user
    FOREIGN KEY (user_id) REFERENCES payroll_v2.users (id)
    ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_user_roles_role
    FOREIGN KEY (role_id) REFERENCES payroll_v2.roles (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_user_roles_role_id ON payroll_v2.user_roles (role_id);

CREATE TABLE IF NOT EXISTS payroll_v2.audit_logs (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT       NOT NULL,
  action      VARCHAR(100) NOT NULL,
  entity_type VARCHAR(100) NOT NULL,
  entity_id   BIGINT       NOT NULL,
  old_values  JSONB        NULL,
  new_values  JSONB        NULL,
  ip_address  VARCHAR(45)  NULL,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_audit_logs_user
    FOREIGN KEY (user_id) REFERENCES payroll_v2.users (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_audit_logs_user_id ON payroll_v2.audit_logs (user_id);
CREATE INDEX IF NOT EXISTS idx_audit_logs_entity ON payroll_v2.audit_logs (entity_type, entity_id);
CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at ON payroll_v2.audit_logs (created_at);

CREATE TABLE IF NOT EXISTS payroll_v2.notifications (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT       NOT NULL,
  title       VARCHAR(200) NOT NULL,
  message     TEXT         NOT NULL,
  entity_type VARCHAR(50)  NULL,
  entity_id   BIGINT       NULL,
  is_read     BOOLEAN      NOT NULL DEFAULT FALSE,
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_notifications_user
    FOREIGN KEY (user_id) REFERENCES payroll_v2.users (id)
    ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_notifications_user_unread ON payroll_v2.notifications (user_id, is_read);

-- =============================================================================
-- 2. ORGANIZATIONAL UNITS, SIGNATORIES, APPOINTMENTS & PAY COMPONENTS
-- =============================================================================

CREATE TABLE IF NOT EXISTS payroll_v2.offices (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code         VARCHAR(50)  NOT NULL UNIQUE,
  name         VARCHAR(200) NOT NULL,
  head_user_id BIGINT       NULL,
  CONSTRAINT fk_offices_head_user
