CREATE INDEX IF NOT EXISTS idx_cc_signatories_user_id ON payroll_v2.cost_center_signatories (user_id);

CREATE TABLE IF NOT EXISTS payroll_v2.funds (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code         VARCHAR(50)  NOT NULL UNIQUE, -- 01, 05, 07
  name         VARCHAR(200) NOT NULL,
  slip_type_id BIGINT       NOT NULL,
  CONSTRAINT fk_funds_slip_type
    FOREIGN KEY (slip_type_id) REFERENCES payroll_v2.slip_types (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_funds_slip_type_id ON payroll_v2.funds (slip_type_id);

CREATE TABLE IF NOT EXISTS payroll_v2.payroll_periods (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label               VARCHAR(100) NOT NULL,
  period_start        DATE         NOT NULL,
  period_end          DATE         NOT NULL,
  submission_deadline DATE         NOT NULL,
  status_id           BIGINT       NOT NULL,
  CONSTRAINT fk_payroll_periods_status
    FOREIGN KEY (status_id) REFERENCES payroll_v2.statuses (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_payroll_periods_status_id ON payroll_v2.payroll_periods (status_id);

CREATE TABLE IF NOT EXISTS payroll_v2.appointments (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id        BIGINT         NOT NULL,
  office_id          BIGINT         NOT NULL,
  cost_center_id     BIGINT         NOT NULL,
  fund_id            BIGINT         NOT NULL,
  employment_type_id BIGINT         NOT NULL,
  position_title     VARCHAR(150)   NOT NULL,
  salary_grade       VARCHAR(20)    NULL,
  step_increment     INTEGER        NULL,
  monthly_rate       NUMERIC(14, 2) NULL,
  daily_rate         NUMERIC(14, 2) NULL,
  hourly_rate        NUMERIC(14, 2) NULL,
  effective_from     DATE           NOT NULL,
  effective_to       DATE           NULL,
  CONSTRAINT fk_appointments_employee
    FOREIGN KEY (employee_id) REFERENCES payroll_v2.employees (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_appointments_office
    FOREIGN KEY (office_id) REFERENCES payroll_v2.offices (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_appointments_cost_center
    FOREIGN KEY (cost_center_id) REFERENCES payroll_v2.cost_centers (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_appointments_fund
    FOREIGN KEY (fund_id) REFERENCES payroll_v2.funds (id)
    ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_appointments_employment_type
    FOREIGN KEY (employment_type_id) REFERENCES payroll_v2.employment_types (id)
    ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_appointments_employee_id ON payroll_v2.appointments (employee_id);
CREATE INDEX IF NOT EXISTS idx_appointments_office_id ON payroll_v2.appointments (office_id);
CREATE INDEX IF NOT EXISTS idx_appointments_cost_center_id ON payroll_v2.appointments (cost_center_id);
CREATE INDEX IF NOT EXISTS idx_appointments_fund_id ON payroll_v2.appointments (fund_id);
CREATE INDEX IF NOT EXISTS idx_appointments_employment_type_id ON payroll_v2.appointments (employment_type_id);

CREATE TABLE IF NOT EXISTS payroll_v2.pay_components (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code         VARCHAR(50)  NOT NULL UNIQUE,
  name         VARCHAR(150) NOT NULL,
  type         VARCHAR(20)  NOT NULL CHECK (type IN ('EARNING', 'ALLOWANCE', 'DEDUCTION', 'ADJUSTMENT')),
  is_statutory BOOLEAN      NOT NULL DEFAULT FALSE,
  calc_method  VARCHAR(20)  NOT NULL CHECK (calc_method IN ('FIXED', 'PERCENT', 'TABLE'))
);

CREATE TABLE IF NOT EXISTS payroll_v2.employee_components (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id    BIGINT         NOT NULL,
  component_id   BIGINT         NOT NULL,
