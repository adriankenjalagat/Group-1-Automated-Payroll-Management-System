CREATE INDEX IF NOT EXISTS idx_doc_submissions_submitted_by ON payroll_v2.document_submissions (submitted_by);
CREATE INDEX IF NOT EXISTS idx_doc_submissions_status_id ON payroll_v2.document_submissions (status_id);

