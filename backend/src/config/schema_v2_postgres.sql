);
CREATE INDEX IF NOT EXISTS idx_offices_head_user_id ON payroll_v2.offices (head_user_id);

CREATE TABLE IF NOT EXISTS payroll_v2.cost_centers (
  id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(50)  NOT NULL UNIQUE,
  name VARCHAR(200) NOT NULL
);

CREATE TABLE IF NOT EXISTS payroll_v2.cost_center_signatories (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cost_center_id  BIGINT       NOT NULL,
  user_id         BIGINT       NOT NULL,
  document_type   VARCHAR(20)  NOT NULL CHECK (document_type IN ('PAYROLL', 'ORAS', 'BURAS', 'DV', 'ADA', 'ADCA')),
  signatory_order INTEGER      NOT NULL DEFAULT 1,
